def main() -> None:
    R = read_results()
    REPORTS.mkdir(parents=True, exist_ok=True)
    (REPORTS / "RESULTS.md").write_text(results_md(R), encoding="utf-8")
    (REPORTS / "REPORT.md").write_text(report_md(R), encoding="utf-8")
    missing = [f for f in ("dendrogram.png", "sector_confusion.png", "proj_gics.png", "proj_kmeans.png", "kmeans_scan.png")
               if not (REPORTS / "figures" / f).exists()]
    print("report written; missing figures:", missing or "none")


if __name__ == "__main__":
    main()
